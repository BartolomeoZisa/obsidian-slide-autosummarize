import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { promises as fs } from "fs";
import { createRequire } from "module";

const require = createRequire(import.meta.url);

/**
 * Bundle pdf.js's worker as inline TEXT so the plugin ships a single
 * main.js. At runtime we turn it into a Blob URL for workerSrc — no
 * separate worker file, no network needed inside Obsidian.
 */
const pdfWorkerTextPlugin = {
	name: "pdf-worker-text",
	setup(build) {
		build.onResolve({ filter: /pdf\.worker\.min\.mjs$/ }, (args) => {
			if (!args.path.includes("pdf.worker")) return null;
			return {
				path: require.resolve(args.path, { paths: [args.resolveDir] }),
				namespace: "pdf-worker-text",
			};
		});
		build.onLoad({ filter: /.*/, namespace: "pdf-worker-text" }, async (args) => ({
			contents: await fs.readFile(args.path, "utf8"),
			loader: "text",
		}));
	},
};

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, visit the plugin's github repository.
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	loader: { ".mjs": "js" },
	plugins: [pdfWorkerTextPlugin],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
